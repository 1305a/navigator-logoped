function cleanPhrase(phrase: string): string {
  return phrase
    .replace(/\s*\*?\([^)]*\)\*?/g, "")
    .replace(/\s+/g, " ")
    .replace(/\.+$/g, "")
    .trim();
}

const imageModules = import.meta.glob("../assets/phrase-image-match/*.png", {
  eager: true,
  import: "default",
}) as Record<string, string>;

function resolveImage(fileName: string): string {
  const key = Object.keys(imageModules).find((k) => k.endsWith(`/${fileName}`));
  return key ? imageModules[key] : "";
}

type RawPhrase = [phrase: string, image: string];
type RawTask = RawPhrase[];

function buildLevel(id: 1 | 2 | 3, raw: RawTask[]): PhraseImageLevel {
  return {
    id,
    tasks: raw.map((phrases, idx) => ({
      id: idx + 1,
      phrases: phrases.map(([phrase, image]) => ({
        phrase: cleanPhrase(phrase),
        image: resolveImage(image),
      })),
    })),
  };
}

