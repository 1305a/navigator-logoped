function withProgress(
  patientId: string,
  pool: string[],
  sessionCount: number,
  grades: number[],
): TherapySession[] {
  const sessions = buildSessions(patientId, pool, sessionCount);
  return sessions.map((s, i) => {
    if (i >= grades.length) return s;
    return {
      ...s,
      grade: grades[i],
      completedDate: "28.07.2026",
      exercises: s.exercises.map((ex) => ({ ...ex, done: true })),
    };
  });
}

